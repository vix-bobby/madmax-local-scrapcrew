"""Generate the proxy's export list from the export table of a real winhttp.dll.

    python3 -I gen_exports.py [path/to/winhttp.dll]

Writes src/winhttp.def and src/exports.h, which are kept in git so that building does not
need a Windows installation. Names listed in WRAPPED go to a C function (src/trace.c);
every other export goes to a stub that jumps straight to the real one.
"""
import struct
import sys
from pathlib import Path

DEFAULT_DLL = "/mnt/c/Windows/System32/winhttp.dll"

# the functions MadMax.exe imports
WRAPPED = (
    "WinHttpAddRequestHeaders",
    "WinHttpCheckPlatform",
    "WinHttpCloseHandle",
    "WinHttpConnect",
    "WinHttpOpen",
    "WinHttpOpenRequest",
    "WinHttpQueryDataAvailable",
    "WinHttpQueryHeaders",
    "WinHttpReadData",
    "WinHttpReceiveResponse",
    "WinHttpSendRequest",
    "WinHttpSetOption",
    "WinHttpSetStatusCallback",
    "WinHttpSetTimeouts",
)


def read_exports(data):
    """Return [(ordinal, name or None)] for a 64-bit PE image, in ordinal order."""
    def u16(at):
        return struct.unpack_from("<H", data, at)[0]

    def u32(at):
        return struct.unpack_from("<I", data, at)[0]

    pe = u32(0x3C)
    if data[pe:pe + 4] != b"PE\0\0" or u16(pe + 4) != 0x8664:
        raise SystemExit("not a 64-bit PE file")
    optional = pe + 24
    sections = []
    for i in range(u16(pe + 6)):
        at = optional + u16(pe + 20) + 40 * i
        size, address, raw_size, raw = struct.unpack_from("<IIII", data, at + 8)
        sections.append((address, max(size, raw_size), raw))

    def offset(rva):
        for address, size, raw in sections:
            if address <= rva < address + size:
                return rva - address + raw
        raise SystemExit(f"address {rva:#x} is outside every section")

    directory = offset(u32(optional + 112))
    base, functions, names = (u32(directory + n) for n in (16, 20, 24))
    function_table, name_table, ordinal_table = (offset(u32(directory + n)) for n in (28, 32, 36))
    by_index = {}
    for i in range(names):
        at = offset(u32(name_table + 4 * i))
        by_index[u16(ordinal_table + 2 * i)] = data[at:data.index(b"\0", at)].decode("ascii")
    return [(base + i, by_index.get(i)) for i in range(functions) if u32(function_table + 4 * i)]


def main():
    source = Path(sys.argv[1] if len(sys.argv) > 1 else DEFAULT_DLL)
    exports = read_exports(source.read_bytes())
    missing = set(WRAPPED) - {name for _, name in exports}
    if missing:
        raise SystemExit(f"not exported by {source}: {', '.join(sorted(missing))}")
    if any(name is None for _, name in exports):
        raise SystemExit("exports without a name are not supported")

    note = "Generated by gen_exports.py. Do not edit."
    definition = [f"; {note}", "LIBRARY winhttp.dll", "EXPORTS"]
    header = [f"/* {note} */", "/* X(index, name) for every export; S(index, name) for those without a wrapper */"]
    all_rows, stub_rows = [], []
    for index, (ordinal, name) in enumerate(exports):
        target = f"hk_{name}" if name in WRAPPED else f"fw_{name}"
        definition.append(f"    {name} = {target} @{ordinal}")
        all_rows.append(f"    X({index}, {name})")
        if name not in WRAPPED:
            stub_rows.append(f"    S({index}, {name})")
    header.append(f"#define EXPORT_COUNT {len(exports)}")
    header.append("#define ALL_EXPORTS(X) \\\n" + " \\\n".join(all_rows))
    header.append("#define STUB_EXPORTS(S) \\\n" + " \\\n".join(stub_rows))

    out = Path(__file__).resolve().parent / "src"
    (out / "winhttp.def").write_text("\n".join(definition) + "\n", encoding="ascii")
    (out / "exports.h").write_text("\n".join(header) + "\n", encoding="ascii")
    print(f"{len(exports)} exports, {len(WRAPPED)} wrapped")


if __name__ == "__main__":
    main()
